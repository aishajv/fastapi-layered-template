PROJECT_ROOT = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class CheckDefinition:
    id: str
    group: str
    label: str
    setup: str
    command: str
    expected: str
    action: Callable[[], str]


@dataclass(frozen=True)
class CheckResult:
    definition: CheckDefinition
    status: str
    observed: str
    detail: str = ""


def run_command(command: list[str]) -> str:
    result = subprocess.run(
        command,
        cwd=PROJECT_ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=300,
    )
    if result.returncode:
        raise RuntimeError(f"Command failed ({' '.join(command)}):\n{result.stdout}")
    return result.stdout


def project_name() -> str:
    pyproject = tomllib.loads((PROJECT_ROOT / "pyproject.toml").read_text())
    return str(pyproject["tool"]["poetry"]["name"])


def check_rendered_project() -> str:
    unresolved_files = []
    markers = ("{" + "{", "{" + "%")
    excluded_parts = {
        ".git",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".venv",
        "acceptance",
    }
    for path in PROJECT_ROOT.rglob("*"):
        if not path.is_file():
            continue
        relative_path = path.relative_to(PROJECT_ROOT)
        if excluded_parts.intersection(relative_path.parts):
            continue
        try:
            content = path.read_text()
        except UnicodeDecodeError:
            continue
        if any(marker in content for marker in markers):
            unresolved_files.append(relative_path.as_posix())
    if unresolved_files:
        raise RuntimeError(f"Unresolved template markers: {unresolved_files}")
    return f"{project_name()} contains no unresolved template markers."


def check_git_hooks() -> str:
    if not (PROJECT_ROOT / ".git").is_dir():
        raise RuntimeError("Git is not initialized.")
    for hook in ("pre-commit", "pre-push"):
        hook_path = PROJECT_ROOT / ".git/hooks" / hook
        if not hook_path.is_file() or not os.access(hook_path, os.X_OK):
            raise RuntimeError(f"The {hook} hook is not installed and executable.")
    return "Git is initialized and both hooks are executable."


def check_poetry_lock() -> str:
    run_command(["poetry", "check", "--lock"])
    return "Poetry metadata and the lock file agree."


def check_static_quality() -> str:
    run_command(["make", "check"])
    return "Ruff formatting, Ruff linting, and strict MyPy passed."


def check_application() -> str:
    run_command(["make", "test"])
    return "The FastAPI health integration test passed."


def check_compose() -> str:
    run_command(["docker", "compose", "config", "--quiet"])
    return "Docker Compose resolved without configuration errors."


