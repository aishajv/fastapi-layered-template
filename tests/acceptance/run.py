def print_progress(completed: int, result: CheckResult, elapsed: float) -> None:
    filled = round(12 * completed / len(CHECKS))
    bar = "█" * filled + "░" * (12 - filled)
    print(
        f"[{completed}/{len(CHECKS)}] {bar} {result.status:<6} "
        f"{result.definition.id} {result.definition.label} ({elapsed:.1f}s)"
    )


def run_checks() -> list[CheckResult]:
    results = []
    print(f"\nChecking {project_name()}…")
    for completed, check in enumerate(CHECKS, start=1):
        print(f"\nRunning {check.id} · {check.label}")
        print(f"  {check.command}")
        started_at = time.monotonic()
        try:
            result = CheckResult(check, "passed", check.action())
        except Exception:
            result = CheckResult(
                check,
                "failed",
                "Failed. Open the report for diagnostics.",
                traceback.format_exc(),
            )
        print_progress(completed, result, time.monotonic() - started_at)
        results.append(result)
    return results


def render_case(result: CheckResult) -> str:
    check = result.definition
    diagnostics = (
        f"<section><h3>Diagnostics</h3><pre>{html.escape(result.detail)}</pre></section>"
        if result.detail
        else ""
    )
    return f"""
      <details class="case {result.status}">
        <summary><span class="case-id">{check.id}</span><span>{html.escape(check.label)}</span>
          <strong>{result.status}</strong><span class="chevron">›</span></summary>
        <div class="detail">
          <section><h3>Setup</h3><p>{html.escape(check.setup)}</p></section>
          <section><h3>Command</h3><pre>{html.escape(check.command)}</pre></section>
          <section><h3>Expected</h3><p>{html.escape(check.expected)}</p></section>
          <section class="result"><h3>Result</h3><p>{html.escape(result.observed)}</p></section>
          {diagnostics}
        </div>
      </details>
    """


def render_groups(results: list[CheckResult]) -> str:
    groups = []
    for group in dict.fromkeys(result.definition.group for result in results):
        group_results = [result for result in results if result.definition.group == group]
        cases = "".join(render_case(result) for result in group_results)
        groups.append(
            f'<section class="group"><div class="group-title"><h2>{group}</h2>'
            f"<span>{len(group_results)} checks</span></div>{cases}</section>"
        )
    return "".join(groups)


def write_report(results: list[CheckResult]) -> Path:
    default_path = Path(tempfile.gettempdir()) / "fastapi-generated-repository-validation.html"
    report_path = Path(os.environ.get("PROJECT_REPORT_PATH", default_path))
    passed = sum(result.status == "passed" for result in results)
    blockers = len(results) - passed
    report_title = f"FastAPI Starter Check: {html.escape(project_name())}"
    report_path.write_text(
        f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{report_title}</title><style>{REPORT_STYLES}</style></head>
<body><main><h1>{report_title}</h1>
<p>A fresh FastAPI repository that installs, tests, and runs.</p>
<div class="summary"><strong>{passed}/{len(results)} passed</strong> · {blockers} blockers</div>
{render_groups(results)}</main></body></html>"""
    )
    return report_path


def open_report(report_path: Path) -> None:
    if os.environ.get("CI"):
        return
    try:
        if not webbrowser.open(report_path.as_uri()):
            print("The browser did not open; use the report link above.")
    except webbrowser.Error:
        print("The browser did not open; use the report link above.")


def main() -> int:
    results = run_checks()
    report_path = write_report(results)
    passed = sum(result.status == "passed" for result in results)
    print()
    if passed == len(results):
        print(f"All set — {project_name()} is ready.")
    else:
        print(f"Setup needs attention — {len(results) - passed} checks failed.")
    print(f"{passed}/{len(results)} checks passed")
    print(f"Visual report: {report_path.as_uri()}")
    open_report(report_path)
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
